/**
 * Entidad GEO derivada del SSOT (#140).
 *
 * El sitio publicaba un `Person` escrito a mano que contradecía al SSOT
 * (`jobTitle`, `@id`, `description`, `sameAs`, FAQ) y ninguna política IA. Estos
 * tests fijan el contrato del bloque publicado — no el contenido del SSOT, que
 * vive en `profile-data` y se congela en `entity.generated.ts`:
 *
 *   1. `assembleHtml()` publica EXACTAMENTE un `Person` (con `@id`, `description`,
 *      `jobTitle`, `email` y los 12 `sameAs`) y un `FAQPage` con 4 preguntas.
 *   2. el bloque no se escribe a mano en `head_html.ts` (sin `jobTitle`/`sameAs`
 *      literales, sin el `"Independent Researcher"` que contradecía al SSOT).
 *   3. el snapshot es determinista y su header no miente sobre la procedencia.
 */
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";
import { assembleHtml } from "../templates/index";
import { ENTITY } from "./entity.generated";

const HEAD_TEMPLATE = readFileSync(resolve(process.cwd(), "src", "templates", "head_html.ts"), "utf8");
const ENTITY_SOURCE = readFileSync(resolve(process.cwd(), "src", "data", "entity.generated.ts"), "utf8");
const HTML = assembleHtml();

interface JsonLdNode {
  "@type"?: string;
  "@graph"?: JsonLdNode[];
  [key: string]: unknown;
}

/** Todos los bloques `application/ld+json` del HTML ensamblado, parseados. */
function jsonLdBlocks(html: string): JsonLdNode[] {
  const blocks: JsonLdNode[] = [];
  const re = /<script type="application\/ld\+json">\n([\s\S]*?)\n<\/script>/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(html))) blocks.push(JSON.parse(m[1]) as JsonLdNode);
  return blocks;
}

/** Nodos de primer nivel (un bloque puede ser un nodo suelto o un `@graph`). */
function topLevelNodes(html: string): JsonLdNode[] {
  return jsonLdBlocks(html).flatMap((node) => (node["@graph"] ? node["@graph"] : [node]));
}

const PERSON = ENTITY.nodes.find((node) => node["@type"] === "Person")!;
const FAQ = ENTITY.nodes.find((node) => node["@type"] === "FAQPage")!;

describe("JSON-LD de la entidad — derivado del SSOT, no escrito a mano", () => {
  it("publica exactamente un bloque Person y un bloque FAQPage", () => {
    const nodes = topLevelNodes(HTML);
    expect(nodes.filter((node) => node["@type"] === "Person")).toHaveLength(1);
    expect(nodes.filter((node) => node["@type"] === "FAQPage")).toHaveLength(1);
  });

  it("el Person lleva el @id canónico y los campos que el SSOT define", () => {
    const person = topLevelNodes(HTML).find((node) => node["@type"] === "Person")!;
    expect(person["@id"]).toBe("https://christianluciani.github.io");
    expect(person["description"]).toEqual(PERSON["description"]);
    expect(person["jobTitle"]).toEqual(PERSON["jobTitle"]);
    expect(person["email"]).toEqual(PERSON["email"]);
    expect(person["sameAs"]).toHaveLength(12);
    // Los 12 sameAs son EXACTAMENTE los del snapshot (ni menos ni otros).
    expect(person["sameAs"]).toEqual(PERSON["sameAs"]);
  });

  it("el FAQPage publica las 4 preguntas con su citation", () => {
    const faq = topLevelNodes(HTML).find((node) => node["@type"] === "FAQPage") as {
      mainEntity: { name: string; acceptedAnswer: { text: string; citation?: string } }[];
    };
    expect(faq.mainEntity).toHaveLength(4);
    for (const question of faq.mainEntity) {
      expect(question.name.length).toBeGreaterThan(0);
      expect(question.acceptedAnswer.text.length).toBeGreaterThan(0);
      expect(question.acceptedAnswer.citation).toMatch(/^https?:\/\//);
    }
  });

  it("no hay ningún campo de la persona escrito a mano en head_html.ts", () => {
    // Los campos del Person viven en entity.generated.ts: si reaparecen acá, el
    // bloque volvió a duplicar el SSOT y este test lo dice.
    expect(HEAD_TEMPLATE).not.toContain('"jobTitle"');
    expect(HEAD_TEMPLATE).not.toContain('"sameAs"');
    expect(HEAD_TEMPLATE).not.toContain("Independent Researcher");
    // El bloque Person YA NO existe como literal: los nodos se interpolan.
    expect(HEAD_TEMPLATE).toContain("${jsonLdBlocks()}");
  });

  it("el ensamblado es determinista (dos corridas byte-idénticas)", () => {
    expect(assembleHtml()).toBe(assembleHtml());
  });
});

describe("entity.generated.ts — procedencia y contrato", () => {
  it("el header declara pin, engine y schema, y coincide con ENTITY.source", () => {
    const header = ENTITY_SOURCE.split("\n").slice(0, 4).join("\n");
    expect(header).toMatch(/^\/\/ AUTO-GENERATED by tools\/sync-entity\.ts — DO NOT EDIT\.$/m);
    expect(header).toMatch(/^\/\/ source: profile-data @ [0-9a-f]{40} · generatedAt null$/m);
    expect(header).toMatch(/^\/\/ engine @ \d+\.\d+\.\d+ · schema v\d+\.\d+$/m);
    expect(header).toContain(`@ ${ENTITY.source.commit}`);
    expect(ENTITY.source.generatedAt).toBeNull();
  });

  it("emite la entidad antes del FAQ (el orden del assembler es el contrato)", () => {
    expect(ENTITY.nodes.map((node) => node["@type"])).toEqual(["Person", "FAQPage"]);
  });

  it("el FAQ no está vacío: el engine nunca emite un FAQPage sin preguntas", () => {
    const faq = FAQ as unknown as { mainEntity: unknown[] };
    expect(faq.mainEntity.length).toBeGreaterThan(0);
  });
});
